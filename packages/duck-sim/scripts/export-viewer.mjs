// Writes viewer/duck-model.js: the bodies, joints, simplified visual
// meshes and part surfaces a browser needs to draw replay frames, as a
// module bundlers and Node both import. Run after `npm run build` whenever
// the robot model changes; a test checks the file is current.

import { writeFile } from 'node:fs/promises';
import { DuckWorld } from '../lib/index.js';
import { meshoptSimplifier } from '../lib/mesh-simplify.js';
import { loadAssets } from '../lib/node-assets.js';

const VIEWER_MAX_ERROR_M = 0.0002; // the test that checks this file uses the same error

const world = await DuckWorld.create(await loadAssets());
const model = world.viewerModel(await meshoptSimplifier(VIEWER_MAX_ERROR_M));
world.dispose();
const out = new URL('../viewer/duck-model.js', import.meta.url);
await writeFile(out, `// Generated by scripts/export-viewer.mjs from the Microduck model; do not edit.\nexport const duckModel = ${JSON.stringify(model)};\nexport default duckModel;\n`);
console.log(`viewer/duck-model.js: ${model.bodies.length} bodies, ${model.geoms.length} geoms, ${model.meshes.length} meshes`);
